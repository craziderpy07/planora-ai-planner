import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import { createServer } from 'node:http';
import { Server } from 'socket.io';
import jwt from 'jsonwebtoken';
import { query, pool } from './db.js';
import authRoutes from './routes/auth.js';
import taskRoutes from './routes/tasks.js';
import externalRoutes from './routes/external.js';
import adminRoutes from './routes/admin.js';
if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) throw new Error('JWT_SECRET must be at least 32 characters');
const app = express(); const server = createServer(app);
const origins = (process.env.CORS_ORIGIN || 'http://localhost:5173').split(',').map(s => s.trim());
const io = new Server(server, { cors: { origin: origins } });
io.use(async (socket, next) => { try { const token = socket.handshake.auth?.token; const payload = jwt.verify(token, process.env.JWT_SECRET, { algorithms: ['HS256'] }); const { rows } = await query('SELECT id FROM users WHERE id=$1', [payload.sub]); if (!rows.length) return next(new Error('Unauthorized')); socket.userId = rows[0].id; next(); } catch { next(new Error('Unauthorized')); } });
io.on('connection', socket => socket.join(`user:${socket.userId}`));
app.use(helmet()); app.use(cors({ origin: origins })); app.use(express.json({ limit: '100kb' }));
app.use((req, res, next) => { req.io = io; next(); });
app.get('/api/health', async (req, res, next) => { try { await query('SELECT 1'); res.json({ status: 'ok', service: 'Planora API', database: 'Neon PostgreSQL' }); } catch (e) { next(e); } });
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: 'draft-7', legacyHeaders: false }), authRoutes);
app.use('/api/tasks', taskRoutes); app.use('/api/external', externalRoutes); app.use('/api/admin', adminRoutes);
app.use((req, res) => res.status(404).json({ error: 'Route not found' }));
app.use((err, req, res, next) => { console.error(err); res.status(500).json({ error: 'Internal server error' }); });
const port = Number(process.env.PORT) || 3000;
server.listen(port, () => console.log(`Planora API running at http://localhost:${port}`));
process.on('SIGTERM', () => { server.close(() => pool.end()); });
